import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
const root=new URL('..',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');
const css=read('offline/source/dark-v13.css');
const shell=read('offline/source/learning-shell.js');
const build=read('offline/build_standalone.py');
const html=read('offline/index.html');
assert.match(css,/color-scheme:dark/);
for(const value of ['#0b0d12','#171a22','#aaa0fa'])assert.ok(css.toLowerCase().includes(value),'missing token '+value);
assert.ok(css.includes('prefers-reduced-motion'));
assert.ok(css.includes('.ws-frame-container iframe{background:white'),'must not affect learner preview');
assert.ok(shell.includes('&lt;/&gt;'),'brand mark');
assert.ok(shell.includes('frontendSummary().done+backendSummary().done'),'real progress');
assert.ok(shell.includes('id="lesson-search"') && shell.includes('event.key.toLowerCase()'), 'global search shortcut');
assert.ok(build.includes('dark-v13.css'),'standalone style integration');
assert.ok(html.includes('data:image/svg+xml'),'embedded SVG favicon');
assert.ok(html.includes('cl-top-search'),'topbar search');
assert.ok(html.includes('v13-home-top'),'dark dashboard');
assert.ok(!shell.includes("save('completed'"),'visual refactor must not write completed lessons');
console.log('OK — tokens dark, marca, favicon, progresso real, busca e build offline.');
