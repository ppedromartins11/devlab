from playwright.sync_api import sync_playwright
from pathlib import Path
HTML=(Path(__file__).parents[1]/'offline/index.html').read_text(encoding='utf-8')
TS=(Path(__file__).parents[1]/'offline/vendor/typescript.js').read_text(encoding='utf-8')
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1200,'height':850})
 errors=[]
 page.on('pageerror',lambda err:errors.append(str(err)))
 page.evaluate('''() => {const store = new Map();Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,String(v)),removeItem:k=>store.delete(k),clear:()=>store.clear()}})}''')
 page.set_content(HTML,wait_until='load')
 page.add_script_tag(content=TS)
 def check(id,code,pass_expected):
  page.evaluate('(id)=>location.hash="#/aula/"+id',id)
  page.locator('.lesson-heading h1').wait_for()
  q=page.evaluate('(id)=>checkpoints[id].answer',id)
  if page.locator('.quiz-choice:not([disabled])').count():
   page.locator(f'[data-answer="{q}"]').first.click()
  page.locator('[data-stage="practice"]').first.click()
  page.locator('#code-editor').fill(code)
  page.wait_for_timeout(850)
  page.locator('[data-action="check-exercise"]').click()
  page.wait_for_function('() => st.checkResult!==null && st.pendingCheck===null',timeout=18000)
  actual=page.evaluate('st.checkResult.passed')
  checks=page.evaluate('st.checkResult.checks.map(x=>(x.ok?"✓ ":"× ")+x.label).join("\\n")')
  print(id, 'OK' if actual==pass_expected else 'FAIL',checks[:350].replace('\n',' | '))
  assert actual==pass_expected,(id,checks)
 check('variaveis', 'function apresentarPerfil(nome,pontos,ativo){return `Olá, ${nome}! Você tem ${pontos} pontos. Status: ${ativo ? "ativo" : "inativo"}.`}',True)
 check('switch','function legendaStatus(status){switch(status){case "pendente":return "Pendente";case "fazendo":return "Em andamento";case "concluida":return "Concluída";default:return "Desconhecido";}}',True)
 check('objetos','function resumirTarefas(tarefas){return tarefas.map(t=>t.titulo+" — "+t.prioridade)}',True)
 check('metodos-array','function resumoTarefas(tarefas){return {pendentes:tarefas.filter(t=>!t.concluida).map(t=>t.titulo),concluidas:tarefas.filter(t=>t.concluida).length}}',True)
 check('strings-numeros',r'function normalizarTitulo(texto){return texto.trim().replace(/\s+/g," ")}',True)
 check('arquitetura','function criarTarefa(id,titulo){const t=titulo.trim();return t?{id,titulo:t,concluida:false}:null}',True)
 check('testes','function tituloValido(texto){return texto.trim().length>0}',True)
 check('ts-intro','function apresentarHoras(nome: string, horas: number): string {return `${nome} estudou ${horas} horas.`}',True)
 check('ts-tipos','function mediaNotas(notas: number[]): number {return notas.length?notas.reduce((a,b)=>a+b,0)/notas.length:0}',True)
 check('ts-interfaces','interface Tarefa {id:number;titulo:string;concluida:boolean;} function titulosPendentes(tarefas: Tarefa[]): string[] {return tarefas.filter(t=>!t.concluida).map(t=>t.titulo)}',True)
 check('ts-funcoes','function percentual(parte: number,total: number): number {return total<=0?0:parte/total*100}',True)
 check('funcoes','function percentual(concluidas,total){return total<=0 ? 0 : concluidas / total * 100;}',True)
 check('funcoes','function percentual(concluidas,total){return 37.5;}',False)
 check('condicionais','function mensagemProgresso(concluidas){if(concluidas<=0)return "Comece agora";if(concluidas<5)return "Continue praticando";return "Excelente progresso"}',True)
 check('assincrono','async function carregarMensagem(nome,atraso){await new Promise(resolve=>setTimeout(resolve,atraso));return "Dados carregados: "+nome}',True)
 check('ts-generics','function primeiro<T>(itens: T[]): T | undefined {return itens[0]}',True)
 check('ts-generics','function primeiro(itens) {return itens[0]}',False)
 check('funcoes','function percentual(concluidas,total){for(let i=0;i>=0;i++) {}}',False)
 assert 'Tempo limite' in page.evaluate('st.checkResult.checks.map(x=>x.label).join(" ")')
 assert not errors,errors
 page.screenshot(path=str(Path(__file__).parents[1]/'devlab7-verificacao.png'),full_page=True)
 print('PASSOU: 18 cenários reais, 15 contratos positivos, JS, TS, async, reprovações e timeout.')
 browser.close()
